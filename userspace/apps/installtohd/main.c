/* InstallToHD.app - install K93OS-x86 onto a hard drive (clean-room).
 * Behaviour (per the project brief): list block devices, let the user pick a
 * target, warn loudly, format it (GPT: 1 GiB swap + rest root filesystem),
 * then copy the running OS payload (kernel + initrd + base system) onto it.
 * Ceiling: the target gets a /boot with kernel+initrd and a grub.cfg; the
 * firmware bootloader chain itself is installed from the host side (see
 * README "Installing to real hardware"). */
#define _GNU_SOURCE
#include "k93ui.h"
#include "k93util.h"
#include "k93gpt.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <errno.h>
#include <dirent.h>
#include <sys/ioctl.h>
#include <sys/mount.h>
#include <sys/stat.h>
#include <sys/wait.h>
#include <linux/fs.h>

#define SWAP_BYTES (1024ULL * 1024 * 1024)               /* 1 GiB */
#define PAYLOAD   "/opt/k93/payload"

struct disk { char dev[32]; char model[64]; unsigned long long sectors; unsigned int ssize; };

static int scan_disks(struct disk *out, int max)
{
    DIR *d = opendir("/sys/block");
    if (!d) return -1;
    struct dirent *e;
    int n = 0;
    while ((e = readdir(d)) && n < max) {
        if (e->d_name[0] == '.') continue;
        /* skip loop/ram/cdrom; keep vd*, sd*, nvme*, hd*, xvd* */
        if (!strncmp(e->d_name, "loop", 4) || !strncmp(e->d_name, "ram", 3) ||
            !strncmp(e->d_name, "sr", 2) || !strncmp(e->d_name, "zram", 4) ||
            !strncmp(e->d_name, "dm-", 3))
            continue;
        char p[256];
        snprintf(p, sizeof p, "/sys/block/%s/size", e->d_name);
        long long sz = k93_sysinfo_long(p);
        if (sz <= 0) continue;
        snprintf(out[n].dev, sizeof out[n].dev, "/dev/%s", e->d_name);
        k93_strlcpy(out[n].model, e->d_name, sizeof out[n].model);
        char mp[256];
        snprintf(mp, sizeof mp, "/sys/block/%s/device/model", e->d_name);
        size_t ml = 0;
        char *m = k93_read_file(mp, &ml);
        if (m) { k93_strlcpy(out[n].model, k93_trim(m), sizeof out[n].model); free(m); }
        out[n].sectors = (unsigned long long)sz;
        out[n].ssize = 512;
        int fd = open(out[n].dev, O_RDONLY);
        if (fd >= 0) {
            int ss = 0;
            if (ioctl(fd, BLKSSZGET, &ss) == 0 && ss > 0) out[n].ssize = (unsigned int)ss;
            close(fd);
        }
        n++;
    }
    closedir(d);
    return n;
}

static int run(char *const argv[])
{
    pid_t p = fork();
    if (p == 0) { execvp(argv[0], argv); _exit(127); }
    int st = 0;
    if (p > 0) waitpid(p, &st, 0);
    return WIFEXITED(st) ? WEXITSTATUS(st) : -1;
}

static int copy_payload(const char *dstroot)
{
    char bootdir[512];
    snprintf(bootdir, sizeof bootdir, "%s/boot", dstroot);
    k93_mkdir_p(bootdir, 0755);
    const char *files[] = { "vmlinuz", "initrd.img", "grub.cfg", NULL };
    int copied = 0;
    for (int i = 0; files[i]; i++) {
        char src[256], dst[512];
        snprintf(src, sizeof src, "%s/%s", PAYLOAD, files[i]);
        snprintf(dst, sizeof dst, "%s/%s", bootdir, files[i]);
        if (access(src, R_OK) == 0) {
            if (k93_copy_file(src, dst, 0644) == 0) copied++;
        }
    }
    /* base system tree */
    const char *dirs[] = { "/Applications", "/bin", "/sbin", "/etc", "/opt",
                           "/System", "/usr", "/lib", "/root", "/home", NULL };
    for (int i = 0; dirs[i]; i++) {
        if (access(dirs[i], F_OK) != 0) continue;
        char dst[512];
        snprintf(dst, sizeof dst, "%s%s", dstroot, dirs[i]);
        if (k93_copy_tree(dirs[i], dst) < 0)
            k93_log("installtohd", "copy %s failed: %s", dirs[i], strerror(errno));
    }
    /* writable skeleton */
    const char *var[] = { "/var/mobile/Media/Downloads", "/var/mobile/Media/Photos",
                          "/var/mobile/Media/Music", "/var/mobile/Library/Notes",
                          "/var/mobile/Library/Calendar", "/var/mobile/Library/Contacts",
                          "/var/log", "/var/db/k93", "/tmp", "/run", NULL };
    for (int i = 0; var[i]; i++) {
        char dst[512];
        snprintf(dst, sizeof dst, "%s%s", dstroot, var[i]);
        k93_mkdir_p(dst, 0777);
    }
    return copied;
}

static void write_fstab(const char *rootdev_swap, const char *rootdev_root)
{
    char buf[512];
    snprintf(buf, sizeof buf,
             "# /etc/fstab generated by InstallToHD\n"
             "%s none swap sw 0 0\n"
             "%s / ext4 defaults,noatime 0 1\n", rootdev_swap, rootdev_root);
    k93_write_file("/mnt/k93new/etc/fstab", buf, strlen(buf), 0);
}

static void write_install_readme(const char *target)
{
    char buf[1024];
    snprintf(buf, sizeof buf,
             "K93OS-x86 installed to %s\n"
             "Layout: GPT; p1 = ext4 root (rest of disk), p2 = 1 GiB swap.\n"
             "Boot files: /boot/vmlinuz, /boot/initrd.img, /boot/grub.cfg.\n"
             "To make it bootable, install a bootloader for your firmware, e.g.\n"
             "  grub2-install --target=x86_64-efi --efi-directory=/boot/efi %s\n"
             "from a live environment, or add a BIOS boot partition and run\n"
             "  grub2-install %s\n", target, target, target);
    char p[512];
    snprintf(p, sizeof p, "%s/etc/k93/INSTALL-README", "/mnt/k93new");
    k93_mkdir_p("/mnt/k93new/etc/k93", 0755);
    k93_write_file(p, buf, strlen(buf), 0);
}

int main(void)
{
    if (ui_init("InstallToHD") < 0) return 1;
    struct disk *disks = k93_xmalloc(sizeof(struct disk) * 32);
    for (;;) {
        int n = scan_disks(disks, 32);
        const char *items[34];
        char labels[32][96];
        for (int i = 0; i < n; i++) {
            char sz[32];
            k93_human_size(sz, sizeof sz, disks[i].sectors * 512ULL);
            snprintf(labels[i], sizeof labels[i], "%s  %8s  %.28s", disks[i].dev, sz, disks[i].model);
            items[i] = labels[i];
        }
        items[n] = "Rescan";
        items[n + 1] = "Cancel";
        int sel = ui_menu("InstallToHD - select target disk", items, n + 2, 0);
        if (sel < 0 || sel == n + 1) break;
        if (sel == n) continue;

        struct disk target = disks[sel];
        char warn[512], sz[32];
        k93_human_size(sz, sizeof sz, target.sectors * 512ULL);
        snprintf(warn, sizeof warn,
                 "WARNING: this ERASES ALL DATA on\n\n  %s  (%s, %s)\n\n"
                 "The disk will be repartitioned as:\n"
                 "  p1  ext4 root filesystem (rest of disk)\n"
                 "  p2  1 GiB swap\n\nContinue?",
                 target.dev, sz, target.model);
        if (!ui_confirm("InstallToHD", warn)) continue;

        /* sanity: not too small */
        unsigned long long bytes = target.sectors * (unsigned long long)target.ssize;
        if (bytes < 512ULL * 1024 * 1024) {
            ui_msgbox("InstallToHD", "Disk is smaller than 512 MiB; refusing.");
            continue;
        }

        ui_statusmsg("Opening target disk ...");
        int fd = open(target.dev, O_RDWR);
        if (fd < 0) {
            char e[128];
            snprintf(e, sizeof e, "Cannot open %s: %s", target.dev, strerror(errno));
            ui_msgbox("InstallToHD", e);
            continue;
        }
        /* confirm the device is a whole disk (partition 1 name ends in 1/5/… only
         * for nvme; we simply require no mounted children) */
        char mounted[256] = "";
        FILE *mf = fopen("/proc/mounts", "r");
        if (mf) {
            char line[256];
            while (fgets(line, sizeof line, mf)) {
                if (strncmp(line, target.dev, strlen(target.dev)) == 0) {
                    k93_strlcpy(mounted, line, sizeof mounted);
                    break;
                }
            }
            fclose(mf);
        }
        if (mounted[0]) {
            ui_msgbox("InstallToHD", "Target (or a partition of it) is mounted.\nUnmount it first.");
            close(fd);
            continue;
        }

        ui_statusmsg("Writing GPT ...");
        uint64_t ssz = target.ssize;
        uint64_t swap_sectors = SWAP_BYTES / ssz;
        if (swap_sectors >= target.sectors / 2) swap_sectors = target.sectors / 4;
        uint64_t first_data = 2048;                        /* 1 MiB alignment */
        uint64_t root_sectors = target.sectors - first_data - swap_sectors - 34;
        if (root_sectors < 2048) { ui_msgbox("InstallToHD", "Disk too small for layout"); close(fd); continue; }

        k93_gpt_part parts[2];
        memset(parts, 0, sizeof parts);
        parts[0].start_sector = first_data;
        parts[0].sector_count = root_sectors;
        k93_strlcpy(parts[0].name, "K93OS root", sizeof parts[0].name);
        parts[0].type_guid = NULL;                        /* default: Linux fs */
        parts[1].start_sector = first_data + root_sectors;
        parts[1].sector_count = swap_sectors;
        k93_strlcpy(parts[1].name, "K93OS swap", sizeof parts[1].name);
        parts[1].type_guid = k93_guid_linux_swap;
        if (k93_gpt_write(fd, (uint32_t)ssz, target.sectors, parts, 2) < 0) {
            ui_msgbox("InstallToHD", "GPT write failed");
            close(fd);
            continue;
        }
        if (k93_gpt_verify(fd, (uint32_t)ssz) < 0) {
            ui_msgbox("InstallToHD", "GPT self-verification failed; aborting");
            close(fd);
            continue;
        }
        close(fd);

        /* partition node names: /dev/vda1 or /dev/nvme0n1p1 */
        char p1[64], p2[64];
        size_t dl = strlen(target.dev);
        char last = target.dev[dl - 1];
        if (last >= '0' && last <= '9') {
            snprintf(p1, sizeof p1, "%sp1", target.dev);
            snprintf(p2, sizeof p2, "%sp2", target.dev);
        } else {
            snprintf(p1, sizeof p1, "%s1", target.dev);
            snprintf(p2, sizeof p2, "%s2", target.dev);
        }
        /* some kernels need a moment to re-read the table */
        for (int i = 0; i < 20 && access(p1, F_OK) != 0; i++) usleep(100000);

        ui_statusmsg("Formatting swap (mkswap) ...");
        char *mkswap[] = { "/bin/busybox", "mkswap", p2, NULL };
        if (run(mkswap) != 0) { ui_msgbox("InstallToHD", "mkswap failed"); continue; }

        ui_statusmsg("Formatting root filesystem (mkfs.ext2, mounted as ext4) ...");
        char *mkfs[] = { "/bin/busybox", "mkfs.ext2", "-q", "-L", "K93OS", p1, NULL };
        if (run(mkfs) != 0) { ui_msgbox("InstallToHD", "mkfs failed"); continue; }

        k93_mkdir_p("/mnt/k93new", 0755);
        ui_statusmsg("Mounting new root ...");
        if (mount(p1, "/mnt/k93new", "ext4", 0, "") < 0) {
            /* ext2 labelled fs may need ext2 type on busybox-only systems */
            if (mount(p1, "/mnt/k93new", "ext2", 0, "") < 0) {
                char e[160];
                snprintf(e, sizeof e, "mount failed: %s", strerror(errno));
                ui_msgbox("InstallToHD", e);
                continue;
            }
        }

        ui_statusmsg("Copying OS payload (kernel, initrd, system) ...");
        int copied = copy_payload("/mnt/k93new");
        write_fstab(p2, p1);
        write_install_readme(target.dev);
        sync();
        umount("/mnt/k93new");

        char done[512], rs[32];
        k93_human_size(rs, sizeof rs, root_sectors * ssz);
        snprintf(done, sizeof done,
                 "Installation complete on %s.\n\n"
                 "%d boot files copied to /boot.\nRoot: %s (%s)\nSwap: %s\n\n"
                 "See /etc/k93/INSTALL-README on the target for bootloader steps.",
                 target.dev, copied, p1, rs, p2);
        ui_msgbox("InstallToHD", done);
    }
    free(disks);
    ui_shutdown();
    return 0;
}
