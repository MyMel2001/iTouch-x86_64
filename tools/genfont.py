#!/usr/bin/env python3
"""Generate userspace font data from the Linux 8x16 console font.

Source: third_party/linux/lib/fonts/font_8x16.c (SPDX-License-Identifier:
GPL-2.0, with the kernel's font-export exception). The generated file keeps
that attribution; the font bitmaps are not original work of this project.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, "r", encoding="ascii", errors="replace").read()
bytes_ = re.findall(r"0x([0-9a-fA-F]{2})", text)
# skip the 4-word font header (0, 0, 4096, 0) - the header uses decimal for
# FONTDATAMAX so only the leading 0x00,0x00 pair needs dropping.
data = bytes(int(b, 16) for b in bytes_[2:])
if len(data) < 4096:
    sys.exit(f"expected >=4096 glyph bytes, got {len(data)}")
data = data[:4096]

with open(dst, "w") as f:
    f.write(
        "/* GENERATED by tools/genfont.py from third_party/linux/lib/fonts/font_8x16.c\n"
        " * SPDX-License-Identifier: GPL-2.0 (Linux console font, exported for reuse).\n"
        " * 256 glyphs, 8x16 bitmaps, row-major, MSB=leftmost pixel. */\n"
        "#include <stdint.h>\n"
        "const uint8_t k93_font8x16[4096] = {\n"
    )
    for i in range(0, 4096, 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"wrote {dst} ({len(data)} bytes)")
